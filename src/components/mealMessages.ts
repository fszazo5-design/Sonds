export type MealMessageCategory = keyof typeof mealMessages;

export function getMealMessageCategory(mealId: string): MealMessageCategory {
  if (mealId === 'breakfast') return 'breakfast';
  if (mealId === 'lunch') return 'lunch';
  if (mealId === 'dinner') return 'dinner';
  return 'snack';
}

export function chooseMealMessage(category: MealMessageCategory, alreadyShown: string[]): string {
  const pool = [...mealMessages[category], ...supportMessages];
  const available = pool.filter((message) => !alreadyShown.includes(message));
  const options = available.length ? available : pool;
  return options[Math.floor(Math.random() * options.length)];
}
